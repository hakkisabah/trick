PROBE_BODY = b"trick storage probe\n"


def probe(backend: BlobBackend, key: str = "_probe/trick-probe.txt") -> dict[str, Any]:
    """Write, read back, compare, delete. Credentials are wrong until this passes.

    A wrong bucket or region usually answers 403 or 301 on write, and a wrong
    secret answers 403 SignatureDoesNotMatch; all of them look identical from a
    distance. A round trip is the only check that distinguishes "I can reach the
    bucket" from "I can use the bucket".
    """
    backend.put(key, PROBE_BODY)
    try:
        back = backend.get(key)
    finally:
        backend.delete(key)
    if back != PROBE_BODY:
        raise StorageIO("the backend returned different bytes than were written")
    return {"ok": True, "backend": backend.name, "probe": key, "verified": True}


def iter_keys(root: Path) -> list[tuple[str, str]]:
    """Every (account, sha) the local index knows about, newest first."""
    out: list[tuple[str, str]] = []
    objects = Path(root) / OBJECTS_DIR
    if not objects.exists():
        return out
    for account_dir in sorted(objects.iterdir()):
        if not account_dir.is_dir():
            continue
        index_path = account_dir / INDEX_NAME
        if not index_path.exists():
            continue
        try:
            index = json.loads(index_path.read_text(encoding="utf-8"))
        except ValueError as exc:
            raise StorageIO(f"{index_path} is not JSON: {exc}") from exc
        entries = index.get("objects") or {}
        if not isinstance(entries, dict):
            raise StorageIO(f"{index_path} has no objects map")
        for sha in sorted(entries):
            out.append((account_dir.name, sha))
    return out


def migrate(
    root: Path,
    target: BlobBackend,
    *,
    source: BlobBackend | None = None,
    keep_source: bool = True,
    dry_run: bool = False,
    target_config: Mapping[str, Any] | None = None,
    progress: Callable[[str], None] | None = None,
) -> dict[str, Any]:
    """Copy every blob to ``target``, verify each one, then switch the config.

    The order is the whole point. Config is rewritten last, so an interrupted
    migration leaves the store pointing at a source that is still complete. Each
    object is read back from the target and hashed before it counts, because a
    migration that trusts a 200 response is how archives disappear.

    Idempotent: objects are content addressed, so a second run overwrites the
    same keys with the same bytes and verifies them again.
    """
    root = Path(root)
    source = source or backend_for_root(root)
    say = progress or (lambda _line: None)
    keys = iter_keys(root)
    plan = {"objects": len(keys), "bytes": 0, "copied": 0, "skipped": 0, "verified": 0, "failed": []}
    for account, sha in keys:
        key = object_key(account, sha)
        try:
            blob = source.get(key)
        except ConfigError:
            plan["failed"].append({"key": key, "reason": "missing in source"})
            continue
        digest = hashlib.sha256(blob).hexdigest()
        if digest != sha:
            plan["failed"].append({"key": key, "reason": "source object does not hash to its name"})
            continue
        plan["bytes"] += len(blob)
        if dry_run:
            plan["skipped"] += 1
            continue
        try:
            target.put(key, blob)
            readback = target.get(key)
        except (StorageIO, ConfigError) as exc:
            # One refused write means the rest will be refused too: stop instead
            # of hammering a locked bucket, and report what was already verified.
            plan["failed"].append({"key": key, "reason": f"{exc.s_code} {exc}"})
            plan["aborted"] = "target refused a write; stopping"
            break
        if hashlib.sha256(readback).hexdigest() != sha:
            plan["failed"].append({"key": key, "reason": "read-back hash mismatch"})
            plan["aborted"] = "read-back mismatch; stopping"
            break
        plan["verified"] += 1
        plan["copied"] += 1
        say(f"copied {key} ({len(blob)} bytes, verified)")
    if plan["failed"]:
        # The config is not touched when anything failed: a half-migrated store
        # that already points at the target is worse than one that never moved.
        return {**plan, "switched": False, "reason": "some objects failed; config left unchanged"}
    if dry_run:
        return {**plan, "switched": False, "reason": "dry run"}
    config = dict(target_config) if target_config else target.describe()
    config.pop("credentials", None)
    config.pop("root", None)
    if config.get("backend") == "s3":
        existing = load_config(root)
        if not config.get("credentials_file") and existing.get("credentials_file"):
            config["credentials_file"] = existing["credentials_file"]
    save_config(root, config)
    if not keep_source:
        for account, sha in keys:
            source.delete(object_key(account, sha))
    return {**plan, "switched": True, "backend": config}
