class BlobBackend:
    """The four operations the store needs. Deliberately small."""

    name = "none"

    def put(self, key: str, blob: bytes) -> None:  # pragma: no cover - interface
        raise NotImplementedError

    def get(self, key: str) -> bytes:  # pragma: no cover - interface
        raise NotImplementedError

    def delete(self, key: str) -> None:  # pragma: no cover - interface
        raise NotImplementedError

    def exists(self, key: str) -> bool:  # pragma: no cover - interface
        raise NotImplementedError

    def describe(self) -> dict[str, Any]:
        return {"backend": self.name}

    def close(self) -> None:
        return None


class FsBackend(BlobBackend):
    """A directory. Atomic, fsynced, 0600 -- the behaviour the store had inline."""

    name = "fs"

    def __init__(self, root: Path) -> None:
        self.root = Path(root)
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        # Keys are generated by object_key(); refuse anything that could escape.
        parts = key.split("/")
        if any(part in {"", ".", ".."} for part in parts):
            raise ContractViolation(f"unsafe object key: {key!r}")
        return self.root.joinpath(*parts)

    def put(self, key: str, blob: bytes) -> None:
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        # A per-writer tmp name: two processes storing the same archive at the
        # same moment must not pick the same temporary path.
        tmp = path.with_suffix(f".{os.getpid()}.{threading.get_ident()}.tmp")
        try:
            tmp.write_bytes(blob)
            os.chmod(tmp, 0o600)
            with open(tmp, "rb") as handle:
                os.fsync(handle.fileno())
            os.replace(tmp, path)
            _fsync_dir(path.parent)
        except OSError as exc:
            tmp.unlink(missing_ok=True)
            raise StorageIO(f"could not write {key}: {exc}") from exc

    def get(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return path.read_bytes()
        except FileNotFoundError as exc:
            raise ConfigError(f"no such object: {key}") from exc
        except OSError as exc:
            raise StorageIO(f"could not read {key}: {exc}") from exc

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink(missing_ok=True)
        except OSError as exc:
            raise StorageIO(f"could not delete {key}: {exc}") from exc

    def exists(self, key: str) -> bool:
        return self._path(key).exists()

    def describe(self) -> dict[str, Any]:
        return {"backend": self.name, "root": str(self.root)}


@dataclass
class S3Settings:
    """Everything except the secret. This is what a user can paste in a bug report."""

    endpoint: str
    bucket: str
    region: str = "us-east-1"
    prefix: str = ""
    addressing: str = "path"
    sse: str = ""
    timeout: float = 20.0
    retries: int = 3
    access_key: str = field(default="", repr=False)
    secret_key: str = field(default="", repr=False)

    def public(self) -> dict[str, Any]:
        return {
            "backend": "s3",
            "endpoint": self.endpoint,
            "bucket": self.bucket,
            "region": self.region,
            "prefix": self.prefix,
            "addressing": self.addressing,
            "sse": self.sse or None,
            "credentials": "present" if self.access_key and self.secret_key else "missing",
        }


def _uri_encode(value: str) -> str:
    return urllib.parse.quote(value, safe="-_.~")


def _canonical_uri(path: str) -> str:
    """S3 signs the path once, not twice; '' means '/'.

    Encoding each segment separately keeps stored slashes structural while
    still escaping anything else that showed up in an account name.
    """
    if not path:
        return "/"
    return "/".join(_uri_encode(part) for part in path.split("/"))


def _canonical_query(query: str) -> str:
    if not query:
        return ""
    pairs = []
    for chunk in query.split("&"):
        key, _, value = chunk.partition("=")
        pairs.append((urllib.parse.unquote_plus(key), urllib.parse.unquote_plus(value)))
    pairs.sort()
    return "&".join(f"{_uri_encode(k)}={_uri_encode(v)}" for k, v in pairs)


def signing_key(secret_key: str, datestamp: str, region: str, service: str) -> bytes:
    """The AWS4 key ladder. Split out so it can be checked against published vectors."""
    k_date = hmac.new(("AWS4" + secret_key).encode("utf-8"), datestamp.encode("utf-8"), hashlib.sha256).digest()
    k_region = hmac.new(k_date, region.encode("utf-8"), hashlib.sha256).digest()
    k_service = hmac.new(k_region, service.encode("utf-8"), hashlib.sha256).digest()
    return hmac.new(k_service, b"aws4_request", hashlib.sha256).digest()


def sign_v4(
    method: str,
    url: str,
    *,
    region: str,
    service: str,
    access_key: str,
    secret_key: str,
    payload_sha: str,
    extra_headers: Mapping[str, str] | None = None,
    now: datetime | None = None,
) -> dict[str, str]:
    """Return the headers that authenticate one request.

    ``payload_sha`` is the real sha256 of the body, not UNSIGNED-PAYLOAD: the
    archive is already hashed by the caller, so the signature also covers the
    bytes. A proxy that swaps the body then breaks the request instead of the
    store silently keeping the wrong archive.
    """
    parts = urllib.parse.urlsplit(url)
    if not parts.netloc:
        raise ConfigError(f"not an absolute url: {url!r}")
    host = parts.netloc
    stamp = (now or datetime.now(timezone.utc)).astimezone(timezone.utc)
    amz_date = stamp.strftime("%Y%m%dT%H%M%SZ")
    datestamp = amz_date[:8]

    headers: dict[str, str] = {
        "host": host,
        "x-amz-content-sha256": payload_sha,
        "x-amz-date": amz_date,
    }
    for name, value in (extra_headers or {}).items():
        headers[name.lower()] = " ".join(value.split())

    signed_names = sorted(headers)
    signed_headers = ";".join(signed_names)
    canonical_headers = "".join(f"{name}:{headers[name]}\n" for name in signed_names)
    canonical_request = "\n".join(
        [method.upper(), _canonical_uri(parts.path), _canonical_query(parts.query), canonical_headers, signed_headers, payload_sha]
    )
    scope = f"{datestamp}/{region}/{service}/aws4_request"
    string_to_sign = "\n".join(
        [
            "AWS4-HMAC-SHA256",
            amz_date,
            scope,
            hashlib.sha256(canonical_request.encode("utf-8")).hexdigest(),
        ]
    )
    signature = hmac.new(
        signing_key(secret_key, datestamp, region, service),
        string_to_sign.encode("utf-8"),
        hashlib.sha256,
    ).hexdigest()
    out = {
        "x-amz-content-sha256": payload_sha,
        "x-amz-date": amz_date,
        "Authorization": (
            f"AWS4-HMAC-SHA256 Credential={access_key}/{scope}, "
            f"SignedHeaders={signed_headers}, Signature={signature}"
        ),
    }
    for name, value in (extra_headers or {}).items():
        out[name] = value
    return out


class S3Backend(BlobBackend):
    """S3 and every server that copied it. Stdlib only: no boto3, no wheel."""

    name = "s3"

    def __init__(self, settings: S3Settings) -> None:
        self.settings = settings
        self._check_endpoint()

    # -- configuration -----------------------------------------------------
    def _check_endpoint(self) -> None:
        parts = urllib.parse.urlsplit(self.settings.endpoint)
        if parts.scheme not in {"http", "https"}:
            raise ConfigError(f"s3 endpoint must be an http(s) url, got {self.settings.endpoint!r}")
        if parts.scheme == "http" and parts.hostname not in LOOPBACK_HOSTS:
            raise ConfigError(
                "plain http is only allowed for a loopback endpoint (a local MinIO); "
                "anything else must be https, or the archive travels next to its token"
            )
        if self.settings.addressing not in {"path", "virtual"}:
            raise ConfigError("addressing must be 'path' or 'virtual'")
        if not self.settings.bucket:
            raise ConfigError("s3 backend needs a bucket name")
        if not self.settings.access_key or not self.settings.secret_key:
            raise ConfigError(
                "s3 backend needs credentials: set TRICK_S3_ACCESS_KEY and TRICK_S3_SECRET_KEY, "
                "or point credentials_file at a 0600 file with KEY=VALUE lines"
            )

    # -- addressing --------------------------------------------------------
    def _url_for(self, key: str) -> str:
        parts = urllib.parse.urlsplit(self.settings.endpoint)
        base_path = parts.path.rstrip("/")
        full_key = "/".join(part for part in (self.settings.prefix.strip("/"), key) if part)
        if self.settings.addressing == "virtual":
            host = f"{self.settings.bucket}.{parts.netloc}"
            path = f"{base_path}/{full_key}"
        else:
            host = parts.netloc
            path = f"{base_path}/{self.settings.bucket}/{full_key}"
        return urllib.parse.urlunsplit((parts.scheme, host, path, "", ""))

    def _connect(self, url: str) -> HTTPConnection:
        parts = urllib.parse.urlsplit(url)
        host = parts.hostname
        if not host:
            raise ConfigError(f"s3 endpoint has no host: {self.settings.endpoint!r}")
        timeout = self.settings.timeout
        if parts.scheme == "https":
            return HTTPSConnection(host, parts.port or 443, timeout=timeout, context=ssl.create_default_context())
        return HTTPConnection(host, parts.port or 80, timeout=timeout)

    # -- one request -------------------------------------------------------
    def _request(self, method: str, key: str, body: bytes | None = None) -> tuple[int, bytes]:
        url = self._url_for(key)
        parts = urllib.parse.urlsplit(url)
        payload = body or b""
        payload_sha = hashlib.sha256(payload).hexdigest()
        extra: dict[str, str] = {}
        if self.settings.sse:
            extra["x-amz-server-side-encryption"] = self.settings.sse
        last: Exception | None = None
        for attempt in range(max(1, self.settings.retries)):
            headers = sign_v4(
                method,
                url,
                region=self.settings.region,
                service=S3_SERVICE,
                access_key=self.settings.access_key,
                secret_key=self.settings.secret_key,
                payload_sha=payload_sha,
                extra_headers=extra,
            )
            conn = self._connect(url)
            path = parts.path + (f"?{parts.query}" if parts.query else "")
            try:
                conn.request(method, path, body=payload if method in {"PUT", "POST"} else None, headers=headers)
                response = conn.getresponse()
                data = response.read()
                status = response.status
            except (OSError, ssl.SSLError) as exc:
                last = exc
                time.sleep(0.2 * (2**attempt))
                continue
            finally:
                conn.close()
            if status in {429, 500, 502, 503, 504} and attempt + 1 < max(1, self.settings.retries):
                time.sleep(0.2 * (2**attempt))
                continue
            return status, data
        raise StorageIO(f"s3 {method} {key} failed after retries: {last}")

    @staticmethod
    def _error(status: int, data: bytes) -> str:
        code = ""
        message = ""
        text = data[:2000].decode("utf-8", "replace")
        for tag, target in (("Code", "code"), ("Message", "message")):
            start = text.find(f"<{tag}>")
            end = text.find(f"</{tag}>")
            if start >= 0 and end > start:
                value = text[start + len(tag) + 2 : end]
                if target == "code":
                    code = value
                else:
                    message = value
        return f"http {status}" + (f" {code}" if code else "") + (f": {message}" if message else "")

    # -- the contract ------------------------------------------------------
    def put(self, key: str, blob: bytes) -> None:
        status, data = self._request("PUT", key, blob)
        if status not in {200, 201, 204}:
            raise StorageIO(f"s3 put {key} refused: {self._error(status, data)}")

    def get(self, key: str) -> bytes:
        status, data = self._request("GET", key)
        if status == 404:
            raise ConfigError(f"no such object: {key}")
        if status != 200:
            raise StorageIO(f"s3 get {key} refused: {self._error(status, data)}")
        return data

    def delete(self, key: str) -> None:
        status, data = self._request("DELETE", key)
        # 404 is success: the object is gone, which is what the caller asked for.
        if status not in {200, 202, 204, 404}:
            raise StorageIO(f"s3 delete {key} refused: {self._error(status, data)}")

    def exists(self, key: str) -> bool:
        status, data = self._request("HEAD", key)
        if status == 200:
            return True
        if status == 404:
            return False
        raise StorageIO(f"s3 head {key} refused: {self._error(status, data)}")

    def describe(self) -> dict[str, Any]:
        return self.settings.public()


def _fsync_dir(path: Path) -> None:
    try:
        fd = os.open(str(path), os.O_RDONLY)
    except OSError:
        return
    try:
        os.fsync(fd)
    except OSError:
        pass
    finally:
        os.close(fd)


