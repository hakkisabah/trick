"""Where the blobs live: a storage backend that can be swapped without a rewrite.

The store keeps two kinds of bytes and they have nothing in common.

* **The index** -- a few kilobytes per account that the server reads, locks with
  ``flock`` and rewrites while it enforces quota. It stays on local disk on
  purpose: object stores have no compare-and-swap, so a quota check in S3 would
  become a race between two uploads that both saw the old usage.
* **The blobs** -- opaque AES-256-GCM archives named by the sha256 of their own
  bytes. They are written once, read rarely, and nothing about them needs a
  filesystem.

Only the second half is pluggable. ``fs`` is the default (a local directory) and
``s3`` speaks the S3 API, which covers AWS S3, MinIO, Cloudflare R2, Backblaze B2
and anything else that copied the protocol. The server process itself does not
change: same routes, same bearer token, same quota logic, same TLS. A backend is
a config line, not a different deployment.

Two rules this module enforces.

1. A secret never lives in ``storage.json``. Credentials come from the
   environment or from a file the server reads at 0600; the config file holds
   bucket names, not keys, because config files get copied into bug reports.
2. Switching backends is a copy plus a read-back verification per object, and
   only then is the config rewritten. ``migrate`` is resumable and never deletes
   the source before the target has been read back byte for byte -- a migration
   that trusts a 200 response is how people lose archives.

Plain HTTP is accepted only for a loopback endpoint (a local MinIO). Anything
else must be TLS, for the same reason the vault server itself refuses to expose
plaintext on a public address.
"""

from __future__ import annotations

