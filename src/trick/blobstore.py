from .errors import ConfigError, ContractViolation, StorageIO

CONFIG_NAME = "storage.json"
INDEX_NAME = "index.json"
OBJECTS_DIR = "objects"
OBJECT_SUFFIX = ".trk"
LOOPBACK_HOSTS = ("127.0.0.1", "::1", "localhost")
S3_SERVICE = "s3"
EMPTY_SHA = hashlib.sha256(b"").hexdigest()
PRESIGN_EXPIRY_MAX = 604_800


# ---------------------------------------------------------------------------
# keys and paths
# ---------------------------------------------------------------------------
def object_key(account: str, sha: str) -> str:
    """One key scheme for every backend, so a migration is a 1:1 copy.

    ``objects/<account>/<sha>.trk`` is what the local layout already used. Reusing
    it in S3 means the same tests, the same debugging and the same restore
    procedure apply to both, instead of two subtly different worlds.
    """
    if not account or "/" in account or account in {".", ".."}:
        raise ConfigError(f"unsafe account name for a storage key: {account!r}")
    if len(sha) != 64 or any(ch not in "0123456789abcdef" for ch in sha):
        raise ContractViolation(f"{sha!r} is not a sha256 hex digest")
    return f"{OBJECTS_DIR}/{account}/{sha}{OBJECT_SUFFIX}"


