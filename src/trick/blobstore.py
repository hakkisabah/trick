def load_config(root: Path) -> dict[str, Any]:
    """Read ``storage.json``. Missing file means the default, not an error.

    That matters for upgrades: a store created before this module existed has no
    config file, and it must keep working as a local directory store.
    """
    path = Path(root) / CONFIG_NAME
    if not path.exists():
        return {"backend": "fs"}
    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except ValueError as exc:
        raise ConfigError(f"{path} is not JSON: {exc}") from exc
    backend = str(raw.get("backend") or "fs").lower()
    if backend not in {"fs", "s3"}:
        raise ConfigError(f"unknown storage backend {backend!r} in {path}")
    return {**raw, "backend": backend}


def save_config(root: Path, config: Mapping[str, Any]) -> Path:
    """Atomic write: a half-written config file is a store that cannot start."""
    path = Path(root) / CONFIG_NAME
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(f".{os.getpid()}.tmp")
    tmp.write_text(json.dumps(dict(config), indent=2, sort_keys=True), encoding="utf-8")
    os.chmod(tmp, 0o600)
    with open(tmp, "rb") as handle:
        os.fsync(handle.fileno())
    os.replace(tmp, path)
    _fsync_dir(path.parent)
    return path


def _read_credentials_file(path: Path) -> dict[str, str]:
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ConfigError(f"cannot read credentials_file {path}: {exc}") from exc
    mode = path.stat().st_mode & 0o777
    if mode & 0o077:
        raise ConfigError(f"credentials_file {path} is mode {mode:o}; it must not be readable by others (chmod 600)")
    values: dict[str, str] = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, _, value = line.partition("=")
        values[name.strip()] = value.strip().strip('"').strip("'")
    return values


def s3_settings(config: Mapping[str, Any]) -> S3Settings:
    endpoint = str(config.get("endpoint") or "").strip()
    if not endpoint:
        raise ConfigError("s3 backend needs an endpoint, e.g. https://s3.eu-central-1.amazonaws.com")
    access_key = os.environ.get("TRICK_S3_ACCESS_KEY", "")
    secret_key = os.environ.get("TRICK_S3_SECRET_KEY", "")
    cred_file = config.get("credentials_file")
    if (not access_key or not secret_key) and cred_file:
        values = _read_credentials_file(Path(str(cred_file)))
        access_key = access_key or values.get("TRICK_S3_ACCESS_KEY", "")
        secret_key = secret_key or values.get("TRICK_S3_SECRET_KEY", "")
    return S3Settings(
        endpoint=endpoint,
        bucket=str(config.get("bucket") or ""),
        region=str(config.get("region") or "us-east-1"),
        prefix=str(config.get("prefix") or ""),
        addressing=str(config.get("addressing") or "path"),
        sse=str(config.get("sse") or ""),
        timeout=float(config.get("timeout") or 20.0),
        retries=int(config.get("retries") or 3),
        access_key=access_key,
        secret_key=secret_key,
    )


def make_backend(config: Mapping[str, Any], root: Path) -> BlobBackend:
    backend = str(config.get("backend") or "fs").lower()
    if backend == "fs":
        # The store root, not its objects/ subdirectory: keys already start with
        # "objects/", and rooting one level deeper would write objects/objects/.
        return FsBackend(Path(root))
    if backend == "s3":
        return S3Backend(s3_settings(config))
    raise ConfigError(f"unknown storage backend {backend!r}")


def backend_for_root(root: Path) -> BlobBackend:
    return make_backend(load_config(root), Path(root))


def config_from_args(backend: str, *, endpoint: str | None, bucket: str | None, region: str | None,
                     prefix: str | None, addressing: str | None, sse: str | None,
                     credentials_file: str | None) -> dict[str, Any]:
    """Build a config dict from CLI arguments, validating as the server would.

    Validation happens here, before anything is written: a config file that only
    fails at the next server start takes the store down instead of failing a
    command.
    """
    if backend == "fs":
        return {"backend": "fs"}
    if backend != "s3":
        raise ConfigError(f"unknown storage backend {backend!r}")
    config: dict[str, Any] = {
        "backend": "s3",
        "endpoint": (endpoint or "").strip(),
        "bucket": (bucket or "").strip(),
        "region": (region or "us-east-1").strip(),
        "prefix": (prefix or "").strip("/"),
        "addressing": (addressing or "path").strip(),
        "sse": (sse or "").strip(),
    }
    if credentials_file:
        config["credentials_file"] = credentials_file
    # Constructing the backend is the validation: endpoint scheme, addressing,
    # bucket and credentials are all checked by _check_endpoint().
    S3Backend(s3_settings(config))
    return config


